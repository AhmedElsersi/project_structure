// Tests for tool/create_feature.dart: runs the generator into a temp project.
//
// Source: new (the generator's core is the importable createFeature()).
import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../../tool/create_feature.dart';

void main() {
  late Directory root;

  setUp(() {
    root = Directory.systemTemp.createTempSync('create_feature_');
    File('${root.path}/pubspec.yaml').writeAsStringSync('name: demo_app\n');
    // Real translation files, so the "append without reordering" rule is
    // checked against the template's own JSON.
    Directory('${root.path}/assets/translations').createSync(recursive: true);
    for (final locale in ['en', 'ar']) {
      File('assets/translations/$locale.json').copySync('${root.path}/assets/translations/$locale.json');
    }
    Directory('${root.path}/lib/features').createSync(recursive: true);
  });

  tearDown(() => root.deleteSync(recursive: true));

  Map<String, dynamic> json(String locale) =>
      jsonDecode(File('${root.path}/assets/translations/$locale.json').readAsStringSync()) as Map<String, dynamic>;

  String read(String relative) => File('${root.path}/lib/features/order_history/$relative').readAsStringSync();

  test('creates the layered feature with all files', () {
    final result = createFeature('order_history', root: root);

    expect(
      result.files,
      containsAll(<String>[
        'lib/features/order_history/data/data_sources/order_history_remote_data_source.dart',
        'lib/features/order_history/data/mock/order_history_mock_api.dart',
        'lib/features/order_history/data/models/order_history_model.dart',
        'lib/features/order_history/data/repositories/order_history_repository_impl.dart',
        'lib/features/order_history/domain/entities/order_history.dart',
        'lib/features/order_history/domain/repositories/order_history_repository.dart',
        'lib/features/order_history/presentation/managers/order_history_cubit.dart',
        'lib/features/order_history/presentation/screens/order_history_screen.dart',
        'lib/features/order_history/presentation/widgets/.gitkeep',
        'lib/features/order_history/order_history_di.dart',
        'lib/features/order_history/order_history_routes.dart',
      ]),
    );
    for (final file in result.files) {
      expect(File('${root.path}/$file').existsSync(), isTrue, reason: file);
    }
    expect(Directory('${root.path}/lib/features/order_history/domain/use_cases').existsSync(), isFalse);

    // Follows the conventions of the items pattern.
    expect(read('data/repositories/order_history_repository_impl.dart'), contains('with RepositoryGuard'));
    expect(read('presentation/managers/order_history_cubit.dart'), contains('extends DataCubit<OrderHistory>'));
    expect(read('presentation/screens/order_history_screen.dart'), contains('LocaleKeys.order_history_title.tr()'));
    expect(read('order_history_routes.dart'), contains("static const path = '/order-history';"));
    expect(
      read('order_history_routes.dart'),
      contains('static List<RouteBase> routes({required GlobalKey<NavigatorState> rootNavigatorKey})'),
    );
    expect(read('order_history_di.dart'), contains('Future<void> registerOrderHistoryFeature()'));
    expect(read('order_history_di.dart'), contains('if (getIt.isRegistered<MockInterceptor>())'));
    // Every generated Dart file has the header and no package: self-import
    // (relative imports survive a package rename).
    for (final file in result.files.where((f) => f.endsWith('.dart'))) {
      final source = File('${root.path}/$file').readAsStringSync();
      expect(source, startsWith('// '), reason: file);
      expect(source, contains('// Source: generated by tool/create_feature.dart'), reason: file);
      expect(source, isNot(contains('package:demo_app/')), reason: file);
      if (file.contains('/domain/')) {
        expect(source, isNot(matches(RegExp('package:(flutter|dio)/'))), reason: 'domain stays pure: $file');
      }
    }
  });

  test('--use-cases adds a use case and injects it into the cubit', () {
    createFeature('order_history', root: root, useCases: true);
    expect(read('domain/use_cases/get_order_history_use_case.dart'), contains('class GetOrderHistoryUseCase'));
    expect(read('presentation/managers/order_history_cubit.dart'), contains('final GetOrderHistoryUseCase'));
    expect(read('order_history_di.dart'), contains('registerLazySingleton<GetOrderHistoryUseCase>'));
  });

  test('appends <name>.title to both locales without touching existing keys', () {
    final enBefore = json('en');
    final arBefore = json('ar');
    final result = createFeature('order_history', root: root);

    expect(result.translationsUpdated, ['en', 'ar']);
    final en = json('en');
    final ar = json('ar');
    expect(en.keys.last, 'order_history');
    expect(en.keys.toList().sublist(0, en.length - 1), enBefore.keys.toList());
    expect(en['order_history'], {'title': 'Order history'});
    // Arabic gets the English text until someone translates it.
    expect(ar['order_history'], {'title': 'Order history'});
    expect(ar.keys.toList().sublist(0, ar.length - 1), arBefore.keys.toList());
    for (final key in enBefore.keys) {
      expect(en[key], enBefore[key]);
    }
  });

  test('prints the wiring lines for main.dart and app_router.dart', () {
    final steps = createFeature('order_history', root: root).nextSteps;
    expect(steps, contains('./tool/gen_locale_keys.sh'));
    expect(steps, contains("import 'features/order_history/order_history_di.dart';"));
    expect(steps, contains('registerOrderHistoryFeature,'));
    expect(steps, contains("import 'features/order_history/order_history_routes.dart';"));
    expect(
      steps,
      contains('StatefulShellBranch(routes: OrderHistoryRoutes.routes(rootNavigatorKey: AppRoutes.rootNavigatorKey)),'),
    );
    expect(steps, contains('...OrderHistoryRoutes.routes(rootNavigatorKey: AppRoutes.rootNavigatorKey),'));
  });

  test('generated code is already dart-format clean for typical names', () async {
    for (final name in ['cart', 'profile', 'order_history', 'notification_settings']) {
      createFeature(name, root: root, useCases: name.length.isEven);
    }
    File('${root.path}/analysis_options.yaml').writeAsStringSync('formatter:\n  page_width: 120\n');
    final result = await Process.run('dart', [
      'format',
      '--output=none',
      '--set-exit-if-changed',
      'lib',
    ], workingDirectory: root.path);
    expect(result.exitCode, 0, reason: '${result.stdout}${result.stderr}');
  });

  test('refuses an existing feature without writing anything', () {
    Directory('${root.path}/lib/features/order_history').createSync();
    final enBefore = File('${root.path}/assets/translations/en.json').readAsStringSync();
    expect(
      () => createFeature('order_history', root: root),
      throwsA(isA<FeatureException>().having((e) => e.message, 'message', contains('already exists'))),
    );
    expect(File('${root.path}/assets/translations/en.json').readAsStringSync(), enBefore);
  });

  test('rejects names that are not snake_case or are reserved', () {
    for (final bad in ['OrderHistory', 'order-history', '1orders', 'orders_', 'order__history', 'class', 'core']) {
      expect(validateFeatureName(bad), isNotNull, reason: bad);
      expect(() => createFeature(bad, root: root), throwsA(isA<FeatureException>()), reason: bad);
    }
    expect(validateFeatureName('orders2'), isNull);
    expect(pascalCase('order_history'), 'OrderHistory');
    expect(sentenceCase('order_history'), 'Order history');
  });
}
